/** اختيار عشوائي مع تجنّب تكرار آخر جملة. */
export function pick(list: readonly string[], lastIndex = -1): { text: string; index: number } {
  if (list.length === 1) return { text: list[0]!, index: 0 };
  let i = Math.floor(Math.random() * list.length);
  if (i === lastIndex) i = (i + 1) % list.length;
  return { text: list[i]!, index: i };
}

