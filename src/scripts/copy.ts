/** جملة اليوم: المربوطة بالتاريخ إن وُجدت، وإلا واحدة من القائمة. */
export function dailyLineFor(dayKey: string): string {
  const pinned = DAILY.special.find((x) => x.date === dayKey);
  if (pinned) return pinned.line;

  // رقم اليوم التقويمي، لا مجموع محارف التاريخ: المجموع توزيعه رديء فتتكرّر
  // جملة كل ثلاثة أيام بينما لا تظهر أخرى أبداً. رقم اليوم يدور على القائمة
  // كاملةً قبل أن يعيد أيّاً منها.
  //
  // `Date.UTC` هنا آمن رغم قاعدة المشروع: `dayKey` تاريخ دمشق محسوبٌ سلفاً،
  // ولا نستعمله كلحظة زمنية بل كعدّاد أيام.
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(dayKey);
  if (!m) return DAILY.lines[0]!;

  const day = Math.floor(Date.UTC(+m[1]!, +m[2]! - 1, +m[3]!) / 86_400_000);
  return DAILY.lines[((day % DAILY.lines.length) + DAILY.lines.length) % DAILY.lines.length]!;
}

