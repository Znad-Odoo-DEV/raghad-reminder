/** جملة اليوم — ثابتة خلال اليوم نفسه، وتتغيّر مع تغيّر التاريخ. */
export function sweetLineFor(dayKey: string): string {
  // مجموع محارف التاريخ يكفي لتوزيع مستقر ومتغيّر يومياً.
  let sum = 0;
  for (let i = 0; i < dayKey.length; i++) sum += dayKey.charCodeAt(i);
  return SWEET.lines[sum % SWEET.lines.length]!;
}

