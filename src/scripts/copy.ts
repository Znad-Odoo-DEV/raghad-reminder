/** اختيار عشوائي بلا تكرار فوري. */
export function pick<T>(list: readonly T[], last = -1): { text: T; index: number } {
  if (list.length === 0) throw new Error('pick: قائمة فارغة');
  if (list.length === 1) return { text: list[0]!, index: 0 };
  let i = last;
  while (i === last) i = Math.floor(Math.random() * list.length);
  return { text: list[i]!, index: i };
}
